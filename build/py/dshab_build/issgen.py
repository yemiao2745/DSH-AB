"""The parts of installer\\dsh-ab.iss that vary per build.

The .iss itself owns the installer script; this module only writes the values that change
from one build to the next (product, both versions, the exe the installer packs, the
artifact name) into installer\\dsh-ab.generated.iss, which the script can pull in with

    #include "dsh-ab.generated.iss"

The same values are handed to ISCC as /D defines. Every define in the generated file is
guarded with #ifndef, so a /D define of the same name wins and both paths agree."""

from pathlib import Path

PAYLOAD = "..\\payload"
APP_EXE_SOURCE = {False: "..\\payload\\DSH_AB.exe", True: "..\\build\\DSH_ABtest.exe"}


def artifact_stem(product_name, dshab_version, dsh_version):
    """The OutputBaseFilename the .iss derives, and therefore the dist\\ artifact name."""
    return "%s-%s-%s-setup" % (product_name, dshab_version, dsh_version)


def defines(dshab_version, dsh_version, test_product):
    args = ["/DDshabVersion=%s" % dshab_version, "/DDshVersion=%s" % dsh_version]
    if test_product:
        args.append("/DTestProduct=1")
    return args


def include_text(product_name, dshab_version, dsh_version, test_product=False,
                 app_exe_source=None):
    source = app_exe_source or APP_EXE_SOURCE[bool(test_product)]
    lines = [
        "; dsh-ab.generated.iss - GENERATED by build/py/build.py for the current build.",
        "; Do not edit: the next build overwrites it. Values that vary per build: the product,",
        "; both versions, the exe the installer packs and the artifact name.",
        "; installer\\dsh-ab.iss can consume it with:  #include \"dsh-ab.generated.iss\"",
        "; Every value is guarded, so an ISCC /D define of the same name still wins.",
        "#ifndef TestProduct",
        "  #define TestProduct %d" % (1 if test_product else 0),
        "#endif",
        "#ifndef DshabVersion",
        '  #define DshabVersion "%s"' % dshab_version,
        "#endif",
        "#ifndef DshVersion",
        '  #define DshVersion "%s"' % dsh_version,
        "#endif",
        "#ifndef AppName",
        '  #define AppName "%s"' % product_name,
        "#endif",
        "#ifndef DefaultDir",
        '  #define DefaultDir "{localappdata}\\%s"' % product_name,
        "#endif",
        "#ifndef AppExeSource",
        '  #define AppExeSource "%s"' % source,
        "#endif",
        "#ifndef Payload",
        '  #define Payload "%s"' % PAYLOAD,
        "#endif",
        "#ifndef SetupFileName",
        '  #define SetupFileName "%s"' % artifact_stem(product_name, dshab_version, dsh_version),
        "#endif",
    ]
    return "\n".join(lines) + "\n"


def write_include(path, product_name, dshab_version, dsh_version, test_product=False):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(include_text(product_name, dshab_version, dsh_version, test_product),
                    encoding="utf-8")
    return path
